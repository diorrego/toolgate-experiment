"""Verify the shared contract manifest and generate its JSON Schema."""
import argparse
import hashlib
import json
from pathlib import Path

import yaml
from jsonschema import Draft202012Validator

ROOT = Path(__file__).resolve().parent.parent
INPUTS = [
    'shared/openapi.yaml', 'shared/mcp-tools.json', 'shared/limits.yaml',
    'shared/PRODUCT.md', 'shared/ARCHITECTURE.md', 'shared/CONTRACT.md',
    'shared/STATE_MACHINE.md', 'shared/SELECTION.md',
    'shared/JSON_SCHEMA_PROFILE.md', 'shared/SECURITY.md', 'shared/DATABASE.md',
]


def encode(value):
    # Manifest serialization only; not a runtime RFC8785 implementation.
    return (json.dumps(value, sort_keys=True, indent=2, ensure_ascii=False) + '\n').encode()


def digest(data):
    return hashlib.sha256(data).hexdigest()


def build_lock(root, paths, version):
    manifest = {
        'format': 'toolgate-reconstructed-contract-lock-v1',
        'contract_version': version,
        'files': {path: digest((root / path).read_bytes()) for path in sorted(paths)},
    }
    return {**manifest, 'sha256': digest(encode(manifest))}


def verify_lock(root, lock):
    manifest = {key: value for key, value in lock.items() if key != 'sha256'}
    if digest(encode(manifest)) != lock['sha256']:
        raise ValueError('Contract manifest digest mismatch')
    for path, expected in lock['files'].items():
        if digest((root / path).read_bytes()) != expected:
            raise ValueError(f'Contract drift: {path}')


def generate_schema(api):
    def rewrite(value):
        if isinstance(value, dict):
            return {key: (item.replace('#/components/schemas/', '#/$defs/')
                          if key == '$ref' else rewrite(item)) for key, item in value.items()}
        if isinstance(value, list):
            return [rewrite(item) for item in value]
        return value
    return {'$schema': 'https://json-schema.org/draft/2020-12/schema',
            '$comment': 'Generated by tools/contract.py; do not edit.',
            '$defs': rewrite(api['components']['schemas'])}


def validate_local_refs(document):
    def walk(value):
        if isinstance(value, dict):
            for key, item in value.items():
                if key == '$ref':
                    if not item.startswith('#/'):
                        raise ValueError('Only local contract refs are allowed')
                    target = document
                    for part in item[2:].split('/'):
                        target = target[part.replace('~1', '/').replace('~0', '~')]
                else:
                    walk(item)
        elif isinstance(value, list):
            for item in value:
                walk(item)
    walk(document)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['check', 'generate', 'lock'])
    args = parser.parse_args()
    api = yaml.safe_load((ROOT / INPUTS[0]).read_text())
    validate_local_refs(api)
    schema = generate_schema(api)
    Draft202012Validator.check_schema(schema)
    validate_local_refs(schema)
    schema_path = ROOT / 'shared/schemas/api.schema.json'
    lock_path = ROOT / 'shared/contract.lock.json'
    if args.action == 'generate':
        schema_path.parent.mkdir(parents=True, exist_ok=True)
        schema_path.write_bytes(encode(schema))
    elif args.action == 'lock':
        if lock_path.exists():
            raise SystemExit('Lock already exists; contract changes require a reviewed migration')
        lock_path.write_bytes(encode(build_lock(ROOT, INPUTS, api['info']['version'])))
    else:
        lock = json.loads(lock_path.read_text())
        if set(lock['files']) != set(INPUTS):
            raise ValueError('Contract manifest file set mismatch')
        verify_lock(ROOT, lock)
        if schema_path.read_bytes() != encode(schema):
            raise ValueError('Generated schema drift; run tools/contract.py generate')
        print(f"Contract {lock['contract_version']} {lock['sha256']}: source lock and generated schema verified")
        print('Static validation only; runtime conformance is a separate gate')


if __name__ == '__main__':
    main()
